# Purpose: Generate standard RF pulse waveforms (no vendor file needed) and write them in the      #
#          formats the simulation engines read. Waveforms are FID-A matrices [phase deg,           #
#          amplitude 0..1, time step, (gradient G/cm)] so they go through the same loader and      #
#          B1 scaling as a vendor file (io_loadRFwaveform / core.rf_pulses).                       #
#                                                                                                  #
#          Shapes: sinc, Gaussian (FID-A rf_gauss, calibrated to its inversion FWHM), HSn          #
#          (Silver 1984; Tannus & Garwood 1997), GOIA-WURST / GOIA-HS / FOCI (Tannus & Garwood     #
