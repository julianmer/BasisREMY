#          the CMRR universal-sLASER formulation. A named catalogue of "standard pulses"           #
#          (STANDARD) resolves a 'standard:<name>' value of 'Path to Pulse' / 'Edit Pulse Path'    #
#          to a generated file in the run's workdir.                                               #
